/**
 * Copies the SVG paths of the brand icons we use from the simple-icons package
 * (CC0) into a small generated module, so only those paths ship to the browser.
 * Run with `npm run icons` after changing the slug list in src/content/brands.ts.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import * as si from "simple-icons";

const brandsFile = path.join(process.cwd(), "src", "content", "brands.ts");
const target = path.join(process.cwd(), "src", "content", "brand-icons.generated.ts");

const source = await readFile(brandsFile, "utf8");
const slugs = [...new Set([...source.matchAll(/slug:\s*"([a-z0-9]+)"/g)].map((m) => m[1]))].sort();

const entries = [];
const missing = [];
for (const slug of slugs) {
  const key = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`;
  const icon = si[key];
  if (!icon) {
    missing.push(slug);
    continue;
  }
  entries.push(`  ${slug}: { title: ${JSON.stringify(icon.title)}, hex: "${icon.hex}", path: ${JSON.stringify(icon.path)} },`);
}
if (missing.length) {
  console.error(`gen-brand-icons: unknown slugs: ${missing.join(", ")}`);
  process.exit(1);
}

const out = `// Generated by scripts/gen-brand-icons.mjs from simple-icons (CC0). Do not edit.
export interface BrandIconData {
  title: string;
  hex: string;
  path: string;
}

export const brandIcons: Record<string, BrandIconData> = {
${entries.join("\n")}
};
`;
await writeFile(target, out);
console.log(`gen-brand-icons: ${entries.length} icons written`);
